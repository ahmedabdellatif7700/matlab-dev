function report_single_case(folder,cfg)
%REPORT_SINGLE_CASE Re-render saved measurements without refitting or retesting.
frozen=jsondecode(fileread(fullfile(folder,"frozen_calibration.json")));
summary=jsondecode(fileread(fullfile(folder,"summary.json")));
s=frozen.settings; fit=frozen.fit;
fitted_gain=fit.effective_gain;
evm=summary.evm_percent; ber=summary.ber;
errors=summary.bit_errors; bits=summary.bits;
load(fullfile(folder,"constellation.mat"),'example');
figure('Visible',cfg.visible,'Position',[100 100 1000 420]); tiledlayout(1,2);
nexttile; scatter(real(example.prediction),imag(example.prediction),2,'.'); hold on;
ideal=qammod((0:s.modulation_order-1).',s.modulation_order,'gray');
plot(real(ideal),imag(ideal),'ko','MarkerSize',7); axis equal; grid on;
xlabel('I'); ylabel('Q'); title({'Unequalized 16-QAM, 400 mVpp';sprintf('Example seed %d',s.validation_seeds(1))});
nexttile; axis off;
text(.03,.9,sprintf('Paper EVM (approx.): %.2f%%\nSimulated EVM: %.4f%%\n\nPaper BER (approx.): %.3e\nSimulated BER: %.3e\nErrors / bits: %d / %d\n\nBoth targets used in calibration.\nMetrics pooled over fresh seeds.', ...
    s.target_evm_percent,evm,s.target_ber,ber,errors,bits),'VerticalAlignment','top','FontSize',11);
exportgraphics(gcf,fullfile(folder,"single_case.png"),'Resolution',170); close(gcf);
markdown=sprintf(join(["# One unequalized operating point\n\n" ...
    "16-QAM, 400 mVpp before the driver, 0.4 Gbaud, 15 km optical-beating A-RoF link. No equalizer or NN.\n\n" ...
    "| Metric | Approximate paper target | Fresh-seed simulation |\n|---|---:|---:|\n" ...
    "| Continuous RMS EVM | %.3f%% | %.5f%% |\n| Gray-bit BER | %.6g | %.6g |\n\n" ...
    "Observed %d errors in %d bits. Nominal 95%% Wilson interval: [%.6g, %.6g]. " ...
    "Bit dependence and only a few seeds limit this interval's interpretation.\n\n" ...
    "Effective driver gain at this one point: %.6g; inferred IF noise PSD: %.6g normalized detector-output units squared/Hz. " ...
    "Effective gain is constrained to 12.5–25, rather than extrapolating a complete amplifier transfer curve. " ...
    "The paper does not report the actual MZM voltage at 400 mVpp; this is an operating-point calibration, not a measured driver model.\n\n" ...
    "**Both EVM and BER targets were used to fit gain and aggregate noise.** Calibration uses a noiseless trace plus Gaussian decision-cell probabilities; validation injects actual real IF noise into the complete link with independent seeds. " ...
    "This is a calibrated single-point match attempt, not independent experimental reproduction. " ...
    "Figures 9 and 11 do not establish a common received optical power; treating the two targets as one condition is explicit. " ...
    "EVM target read-off allowance is ±0.5 percentage points; BER read-off allowance is ±0.06 log10 units.\n\n" ...
    "The optical/RF response, amplitude-envelope detector and noise-budget assumptions remain approximate. " ...
    "Do not extrapolate this calibrated gain to other drives or claim a calibrated optical-power budget.\n\n" ...
    "![Unequalized result](single_case.png)\n"],""), ...
    s.target_evm_percent,evm,s.target_ber,ber,errors,bits,summary.ber_lower,summary.ber_upper,fitted_gain,fit.if_noise_psd);
write_text(fullfile(folder,"README.md"),markdown);
fprintf("Single unequalized case report: %s\n",folder);

end

function write_text(path,value)
[fid,msg]=fopen(path,'w'); assert(fid>=0,'%s',msg);
cleanup=onCleanup(@() fclose(fid)); fprintf(fid,'%s\n',value);
end
